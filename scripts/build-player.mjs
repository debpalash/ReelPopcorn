import {build} from 'esbuild';
import {mkdir,readFile,readdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const tags={youtube:'youtube-video',vimeo:'vimeo-video',twitch:'twitch-video',tiktok:'tiktok-video',spotify:'spotify-audio'};
const bundles={};
const allNotices=new Map();
for(const [provider,tag] of Object.entries(tags)) {
 const result=await build({stdin:{contents:`import '@videojs/html/media/${tag}'; import {installBridge} from './src/media/browser-bridge.js'; installBridge(${JSON.stringify({provider,tag})});`,resolveDir:root},bundle:true,write:false,tsconfigRaw:{compilerOptions:{}},minify:true,format:'iife',platform:'browser',target:['safari17','chrome120'],legalComments:'eof',charset:'ascii',metafile:true});
 const licenses=new Map();
 const packages=new Set(Object.keys(result.metafile.inputs).map(file=>file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean));
 for(const name of [...packages].sort()) {
  const directory=path.join(root,'node_modules',name),info=JSON.parse(await readFile(path.join(directory,'package.json'),'utf8'));
  const file=(await readdir(directory)).find(file=>/^licen[cs]e(?:\.(?:md|txt))?$/i.test(file));
  if(!file)throw new Error(`Missing license for ${name}`);
  const text=(await readFile(path.join(directory,file),'utf8')).trim();
  licenses.set(text,[...(licenses.get(text)||[]),`${name}@${info.version}`]);
  allNotices.set(`${name}@${info.version}`,text);
 }
 const notices=[...licenses].map(([license,names])=>`${names.join(', ')}\n${license}`).join('\n\n');
 bundles[provider]=result.outputFiles[0].text+`\n/* Third-party notices\n${notices.replace(/\*\//g,'* /')}\n*/\n`;
 console.log(`${provider}: ${(Buffer.byteLength(bundles[provider])/1024).toFixed(1)} KB`);
}
await mkdir(path.join(root,'src/generated'),{recursive:true});
const contents=`// Generated by npm run build:player. Bundled Video.js 10.4.0; do not edit.\nexport const PROVIDER_BUNDLES:Record<string,string> = ${JSON.stringify(bundles)};\n`;
const destination=path.join(root,'src/generated/player-bundles.ts');
let previous='';try{previous=await readFile(destination,'utf8');}catch{}
if(previous!==contents)await writeFile(destination,contents);

const noticeFile=path.join(root,'THIRD_PARTY_NOTICES.txt');
const noticeContents=[...allNotices].map(([name,license])=>`${name}\n${license}`).join('\n\n');
let previousNotices='';try{previousNotices=await readFile(noticeFile,'utf8');}catch{}
if(previousNotices!==noticeContents)await writeFile(noticeFile,noticeContents+'\n');
